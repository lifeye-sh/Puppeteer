import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--disable-dev-shm-usage'],env:{...process.env,HOME:'/tmp/browser-home'}});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('https://localhost:8443/',{waitUntil:'networkidle'});
 await page.locator('input[autocomplete="username"]').fill('accept-admin');
 await page.locator('input[autocomplete="current-password"]').fill('R01-test-only-strong-password');
 await page.locator('button[type="submit"]').click();
 await page.waitForURL(u=>!u.pathname.includes('login'),{timeout:20000});
 await page.goto('https://localhost:8443/x-asset',{waitUntil:'networkidle'});
 await page.getByText('R04 test target',{exact:true}).first().waitFor();
 const popup=context.waitForEvent('page');await page.getByRole('link',{name:'终端',exact:true}).first().click();const terminal=await popup;
 await terminal.waitForLoadState('networkidle');
 assert.equal(new URL(page.url()).pathname,'/x-asset');
 await terminal.getByRole('tab',{name:'R04 test target'}).dblclick();
 await terminal.locator('.nt-tab-dot.is-connected').waitFor({timeout:20000});
 await terminal.locator('.xterm-helper-textarea').focus();await terminal.keyboard.type('whoami');await terminal.keyboard.press('Enter');
 await terminal.waitForTimeout(1000);
 // The app's live session endpoint confirms connection and audit data rather than canvas text scraping.
 const sessions=await terminal.evaluate(async()=>{const r=await fetch('/api/sessions');if(!r.ok)throw Error('sessions unavailable');return r.json()});
 assert.ok(JSON.stringify(sessions).includes('connected'));
 const fixture=await terminal.evaluate(async()=>await(await fetch('/api/__fixture/audit')).json());
 await terminal.getByRole('button',{name:'打开文件管理',exact:true}).click();
 await terminal.getByRole('textbox',{name:'目录地址',exact:true}).fill(fixture.fileRoot);
 await terminal.getByRole('button',{name:/^跳\s*转$/}).click();
 await terminal.locator('input[type="file"]').setInputFiles({name:'r17-browser.txt',mimeType:'text/plain',buffer:Buffer.from('R17 browser SFTP proof')});
 await terminal.getByText('r17-browser.txt',{exact:true}).waitFor();
 await terminal.getByRole('textbox',{name:'SFTP 文件名过滤'}).fill('r17-browser');
 const fileDownload=terminal.waitForEvent('download');await terminal.getByRole('button',{name:/^下\s*载$/}).click();
 const downloadedFile=await fileDownload;assert.equal(downloadedFile.suggestedFilename(),'r17-browser.txt');
 assert.equal(await readFile(await downloadedFile.path(),'utf8'),'R17 browser SFTP proof');
 await terminal.keyboard.press('Escape');await terminal.getByRole('dialog').waitFor({state:'hidden'});
 await terminal.getByRole('button',{name:'关闭 R04 test target',exact:true}).click();
 await terminal.close();
 await page.goto('https://localhost:8443/access-log',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'录屏回放',exact:true}).first().click();
 await page.getByText('只读录屏回放',{exact:true}).waitFor();
 await page.getByRole('button',{name:/^播\s*放$/}).click();
 await page.keyboard.press('Escape');await page.getByRole('dialog').waitFor({state:'hidden'});
 await page.getByRole('button',{name:'生成 MP4',exact:true}).first().click();
 const mp4=page.getByRole('link',{name:/下载 MP4/}).first();await mp4.waitFor({timeout:90000});
 const video=page.waitForEvent('download');await mp4.click();const download=await video;assert.ok(download.suggestedFilename().endsWith('.mp4'));await download.saveAs('/evidence/r17-browser.mp4');
 const videoBytes=await readFile('/evidence/r17-browser.mp4');assert.ok(videoBytes.length>1024);assert.equal(videoBytes.toString('ascii',4,8),'ftyp');
 await page.goto('https://localhost:8443/system-status',{waitUntil:'networkidle'});await page.getByRole('heading',{name:'平台设置',exact:true}).waitFor();
 await page.goto('https://localhost:8443/asset',{waitUntil:'networkidle'});await page.getByText('R04 test target',{exact:true}).first().waitFor();
 await page.screenshot({path:'/evidence/r17-browser.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,tlsVerification:true,checks:['login','asset list','terminal opens new tab','WSS SSH connection','command input','SFTP upload/filter/download','tab closes session','recording playback','background MP4 conversion and download','settings/assets render'],pageErrors:errors}));
}catch(e){console.error((await page.locator('body').innerText()).slice(0,2000));throw e}finally{await browser.close()}
