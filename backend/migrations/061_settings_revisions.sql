CREATE TABLE configuration_nodes(id text PRIMARY KEY, last_seen timestamptz NOT NULL DEFAULT now());
CREATE TABLE configuration_acks (
 revision bigint NOT NULL REFERENCES configuration_revisions(id), node_id text NOT NULL REFERENCES configuration_nodes(id),
 state text NOT NULL CHECK(state IN ('requested','effective','failed')), error text NOT NULL DEFAULT '',
 attempts integer NOT NULL DEFAULT 0, updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(revision,node_id)
);
