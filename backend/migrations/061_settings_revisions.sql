CREATE TABLE configuration_revisions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 snapshot jsonb NOT NULL, changed_keys text[] NOT NULL DEFAULT '{}',
 actor_id uuid REFERENCES users(id) ON DELETE SET NULL,
 legacy_write boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL DEFAULT now()
);
